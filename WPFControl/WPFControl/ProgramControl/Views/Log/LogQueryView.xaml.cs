namespace WPFControl.ProgramControl.Views
{
    /// <summary>
    /// LogQueryView.xaml 的交互逻辑
    /// </summary>
    public partial class LogQueryView : UserControl
    {
        public static readonly DependencyProperty FilterColumnSourceProperty = DependencyProperty.Register
            ("FilterColumnSource", typeof(IEnumerable), typeof(LogQueryView), new PropertyMetadata(null));

        [Bindable(true)]
        [Category("自定义属性"), Description("筛查字段集合(来自DataGrid表头)"), DisplayName("筛查字段集合")]
        public IEnumerable FilterColumnSource
        {
            get { return (IEnumerable)GetValue(FilterColumnSourceProperty); }
            set { SetValue(FilterColumnSourceProperty, value); }
        }

        public LogQueryView()
        {
            InitializeComponent();
            View_DataGrid.AutoGeneratedColumns += OnAutoGeneratedColumns;
        }

        private void OnAutoGeneratedColumns(object sender, EventArgs e)
        {
            var headers = new List<string>();
            foreach (var col in View_DataGrid.Columns)
            {
                var header = col.Header?.ToString();
                if (!string.IsNullOrEmpty(header))
                    headers.Add(header);
            }
            FilterColumnSource = headers;
        }
    }
}
