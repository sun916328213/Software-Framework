// 直接导入的协作命名空间包括：Vision.Core、System.ComponentModel、System.Reflection、System.Windows.Controls、System.Windows.Data。导入不代表所有类型都会在运行时加载。
using Vision.Core;
using System.ComponentModel;
using System.Reflection;
using System.Windows.Controls;
using System.Windows.Data;

#nullable enable

namespace Vision.Controls
{
    /// <summary>
    /// PropertyEditorBindingHelper 的类型定义。Vision 模块：视觉工具模型、算法适配和编辑展示；厂商能力与界面转换应在对应边界内协作。
    /// </summary>
    internal static class PropertyEditorBindingHelper
    {
        /// <summary>
        /// 处理当前类型提供的操作；对应入口为 IsEditableProperty。
        /// 正文中的关键协作调用包括 IsToolMetadataProperty；具体条件和先后次序见方法体。
        /// </summary>
        public static bool IsEditableProperty(PropertyInfo? prop)
        {
            if (prop == null) return false;
            if (IsToolMetadataProperty(prop.Name)) return false;

            return prop.CanWrite && prop.SetMethod != null && prop.SetMethod.IsPublic;
        }

        /// <summary>
        /// 处理当前类型提供的操作；对应入口为 IsDisplayableProperty。
        /// 正文中的关键协作调用包括 IsToolMetadataProperty；具体条件和先后次序见方法体。
        /// </summary>
        public static bool IsDisplayableProperty(PropertyInfo? prop, ToolPropertyAttribute? attr)
        {
            if (prop == null || attr == null) return false;
            if (IsToolMetadataProperty(prop.Name)) return false;

            return attr.IsDisplay;
        }

        /// <summary>
        /// 处理当前类型提供的操作；对应入口为 ApplyAutoGeneratedColumnRules。
        /// 正文中的关键协作调用包括 IsToolMetadataProperty、ResolvePropertyInfo、IsEditableProperty、ForceOneWayBinding；具体条件和先后次序见方法体。
        /// </summary>
        public static void ApplyAutoGeneratedColumnRules(DataGridAutoGeneratingColumnEventArgs e)
        {
            if (e == null) return;

            if (IsToolMetadataProperty(e.PropertyName))
            {
                e.Cancel = true;
                return;
            }

            var prop = ResolvePropertyInfo(e);
            if (prop == null || IsEditableProperty(prop)) return;

            e.Column.IsReadOnly = true;
            ForceOneWayBinding(e.Column, e.PropertyName);
        }

        /// <summary>
        /// 处理当前类型提供的操作；对应入口为 IsToolMetadataProperty。
        /// 正文中的关键协作调用包括 Equals；具体条件和先后次序见方法体。
        /// </summary>
        private static bool IsToolMetadataProperty(string propertyName)
        {
            return string.Equals(propertyName, "ToolType", StringComparison.Ordinal);
        }

        /// <summary>
        /// 处理当前类型提供的操作；对应入口为 ResolvePropertyInfo。
        /// </summary>
        private static PropertyInfo? ResolvePropertyInfo(DataGridAutoGeneratingColumnEventArgs e)
        {
            if (e.PropertyDescriptor is PropertyInfo prop)
                return prop;

            if (e.PropertyDescriptor is PropertyDescriptor descriptor)
                return descriptor.ComponentType?.GetProperty(descriptor.Name);

            return null;
        }

        /// <summary>
        /// 处理当前类型提供的操作；对应入口为 ForceOneWayBinding。
        /// 此入口包含异常处理；失败时是上报、恢复还是继续抛出，请以 catch 分支为准。
        /// </summary>
        private static void ForceOneWayBinding(DataGridColumn column, string propertyName)
        {
            if (column is not DataGridBoundColumn boundColumn)
                return;

            if (boundColumn.Binding is Binding binding)
            {
                try
                {
                    binding.Mode = BindingMode.OneWay;
                    return;
                }
                catch (InvalidOperationException)
                {
                    // Binding may already be sealed by WPF; replace it below.
                }
            }

            boundColumn.Binding = new Binding(propertyName)
            {
                Mode = BindingMode.OneWay
            };
        }
    }
}
