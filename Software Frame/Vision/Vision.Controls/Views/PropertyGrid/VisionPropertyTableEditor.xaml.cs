using System.Collections;
using System.Collections.Specialized;
using System.ComponentModel;
using System.Reflection;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Data;
using Vision.Controls.Presentation;
using Vision.Core;

namespace Vision.Controls.View;

/// <summary>属性面板表格编辑器：DataGrid 视觉在 XAML，列与绑定按运行时属性元数据生成。</summary>
public partial class VisionPropertyTableEditor : UserControl
{
    private Action _rowsChanged;
    private INotifyCollectionChanged _observed;

    public VisionPropertyTableEditor() => InitializeComponent();

    internal void ConfigureList(PropertyInfo prop, object target, bool canEdit, bool canChangeRows,
        bool twoWayBinding, Action rowsChanged)
    {
        Table.IsReadOnly = !canEdit;
        Table.CanUserAddRows = canChangeRows;
        Table.CanUserDeleteRows = canChangeRows;
        Table.AutoGenerateColumns = true;
        BindingOperations.SetBinding(Table, ItemsControl.ItemsSourceProperty, new Binding(prop.Name)
        {
            Source = target,
            Mode = twoWayBinding ? BindingMode.TwoWay : BindingMode.OneWay
        });
        Table.SetResourceReference(StyleProperty, "Vision.PropertyPanel.Table");
        _rowsChanged = rowsChanged;
    }

    internal void ConfigureClass(PropertyInfo prop, ToolPropertyAttribute attr, object target, bool canEditItems,
        Action rowsChanged)
    {
        var sourceList = prop.GetValue(target) as IList;
        var canChangeRows = canEditItems && sourceList is { IsReadOnly: false, IsFixedSize: false };
        Table.IsReadOnly = !canEditItems;
        Table.CanUserAddRows = canChangeRows;
        Table.CanUserDeleteRows = canChangeRows;
        Table.AutoGenerateColumns = false;

        var itemType = prop.PropertyType.GenericTypeArguments.FirstOrDefault();
        var captionProperty = string.IsNullOrEmpty(attr.BindingProp) ? null : itemType?.GetProperty(attr.BindingProp);
        Table.Columns.Add(new DataGridTextColumn
        {
            Header = captionProperty?.GetCustomAttribute<ToolPropertyAttribute>()?.DisplayName ?? "项目",
            Binding = new Binding(string.IsNullOrEmpty(attr.BindingProp) ? "." : attr.BindingProp) { Mode = BindingMode.OneWay },
            IsReadOnly = true,
            Width = new DataGridLength(1, DataGridLengthUnitType.Star)
        });
        BindingOperations.SetBinding(Table, ItemsControl.ItemsSourceProperty,
            new Binding(prop.Name) { Source = target, Mode = BindingMode.OneWay });
        if (!string.IsNullOrEmpty(attr.BindingIsHit))
        {
            var style = new Style(typeof(DataGridRow))
            {
                BasedOn = Application.Current.TryFindResource("MaterialDesignDataGridRow") as Style
            };
            style.Setters.Add(new Setter(DataGridRow.IsSelectedProperty,
                new Binding(attr.BindingIsHit) { Mode = BindingMode.OneWay }));
            Table.RowStyle = style;
        }
        Table.SetResourceReference(StyleProperty, "Vision.PropertyPanel.ClassTable");
        _rowsChanged = rowsChanged;
    }

    private void Editor_Loaded(object sender, RoutedEventArgs e) =>
        ObserveRows(Table.Items as INotifyCollectionChanged);

    private void Editor_Unloaded(object sender, RoutedEventArgs e) => ObserveRows(null);

    private void ObserveRows(INotifyCollectionChanged items)
    {
        if (ReferenceEquals(_observed, items)) return;
        if (_observed != null) _observed.CollectionChanged -= Table_RowsChanged;
        _observed = items;
        if (_observed != null) _observed.CollectionChanged += Table_RowsChanged;
    }

    private void Table_RowsChanged(object sender, NotifyCollectionChangedEventArgs e)
    {
        // 不观察 Reset（重载/排序），只把用户增删改行上报给面板。
        if (e.Action is NotifyCollectionChangedAction.Add or NotifyCollectionChangedAction.Remove
            or NotifyCollectionChangedAction.Replace)
            _rowsChanged?.Invoke();
    }

    private void Table_LoadingRow(object sender, DataGridRowEventArgs e) =>
        e.Row.Header = (e.Row.GetIndex() + 1).ToString();

    private void Table_AutoGeneratingColumn(object sender, DataGridAutoGeneratingColumnEventArgs e)
    {
        if (e.PropertyDescriptor is PropertyDescriptor descriptor)
        {
            if (!descriptor.IsBrowsable) { e.Cancel = true; return; }
            e.Column.Header = descriptor.DisplayName;
        }
        PropertyEditorBindingHelper.ApplyAutoGeneratedColumnRules(e);
        if (e.Column is DataGridBoundColumn column && column.Binding is Binding binding)
        {
            binding.UpdateSourceTrigger = UpdateSourceTrigger.PropertyChanged;
            binding.ValidatesOnExceptions = true;
            binding.NotifyOnSourceUpdated = true;
        }
    }
}
